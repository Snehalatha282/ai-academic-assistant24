import pymupdf as fitz
from pathlib import Path

def create_sample_academic_pdf(output_path: str):
    doc = fitz.open()
    
    # Page 1: Module 1 - Virtual Memory & Paging
    page1 = doc.new_page()
    rect = fitz.Rect(50, 50, 550, 750)
    text1 = """SIDDAGANGA INSTITUTE OF TECHNOLOGY
DEPARTMENT OF COMPUTER SCIENCE AND ENGINEERING
COURSE: OPERATING SYSTEMS (21CS42)

MODULE 1: VIRTUAL MEMORY AND PAGING

1.1 Concept of Virtual Memory
Virtual memory is a memory management capability of an operating system that uses hardware and software to allow a computer to compensate for physical memory shortages by temporarily transferring data from random access memory (RAM) to disk storage. It maps virtual addresses used by an application onto physical addresses in computer memory.

1.2 Paging Hardware and Address Translation
Paging is a memory management scheme that eliminates the need for contiguous allocation of physical memory.
- Logical Address: Generated by the CPU, divided into Page Number (p) and Page Offset (d).
- Physical Address: Actual memory location in RAM, divided into Frame Number (f) and Offset (d).
The page size is defined by the hardware and is typically a power of 2 (e.g., 4 KB to 8 KB).
Address Translation Formula:
- Given m-bit logical address and page size 2^n:
  High-order (m - n) bits designate Page Number (p).
  Low-order n bits designate Page Offset (d).
The Page Table maps page number p to frame number f. The physical address is constructed as (f * frame_size) + d.

1.3 Translation Lookaside Buffer (TLB)
A TLB is a high-speed hardware associative cache used to reduce memory access time during paging.
Effective Access Time (EAT) Formula:
EAT = (hit_ratio * (TLB_access_time + Memory_access_time)) + ((1 - hit_ratio) * (TLB_access_time + 2 * Memory_access_time))

1.4 Page Replacement Algorithms
When a page fault occurs and no free frames exist, page replacement algorithms choose a victim frame:
1. FIFO (First-In, First-Out): Replaces the oldest page; subject to Belady's Anomaly.
2. LRU (Least Recently Used): Replaces the page not used for the longest period of time; optimal stack algorithm.
3. Optimal Page Replacement: Replaces the page that will not be used for the longest period in the future (theoretical benchmark).
"""
    page1.insert_textbox(rect, text1, fontsize=10, fontname="helv")

    # Page 2: Module 2 - Process Scheduling & Concurrency
    page2 = doc.new_page()
    text2 = """MODULE 2: PROCESS MANAGEMENT AND CPU SCHEDULING

2.1 Process Concept and State Transitions
A process is a program in execution. Its memory layout contains Text (code), Data (global variables), Heap (dynamically allocated memory), and Stack (local variables, function calls).
Process States:
1. New: The process is being created.
2. Ready: The process is waiting to be assigned to a processor.
3. Running: Instructions are being executed.
4. Waiting/Blocked: The process is waiting for some event or I/O completion.
5. Terminated: The process has finished execution.

2.2 CPU Scheduling Criteria and Algorithms
The CPU scheduler selects from among the processes in memory that are ready to execute:
- CPU Utilization: Keep the CPU as busy as possible (target: 40% to 90%).
- Throughput: Number of processes completed per unit time.
- Turnaround Time: Interval from submission to completion: Turnaround = Completion Time - Arrival Time.
- Waiting Time: Total time spent waiting in ready queue: Waiting = Turnaround Time - Burst Time.
- Response Time: Time from submission until the first response is produced.

Scheduling Algorithms:
- FCFS (First-Come, First-Served): Non-preemptive, suffers from Convoy Effect.
- SJF (Shortest Job First): Provably optimal minimum average waiting time.
- Round Robin (RR): Preemptive, designed for timesharing systems using a fixed Time Quantum (q). If quantum is too large, RR behaves like FCFS; if too small, context-switch overhead dominates.

2.3 The Critical Section Problem
A race condition occurs when multiple processes access and manipulate the same data concurrently.
Requirements for a valid Critical Section solution:
1. Mutual Exclusion: If process Pi is executing in its critical section, no other processes can execute in their critical sections.
2. Progress: If no process is executing in its critical section, only processes not in their remainder sections can participate in deciding who enters next.
3. Bounded Waiting: A bound must exist on the number of times other processes are allowed to enter their critical sections after a process has made a request.
"""
    page2.insert_textbox(rect, text2, fontsize=10, fontname="helv")

    # Page 3: Module 3 - Deadlocks & Banker's Algorithm
    page3 = doc.new_page()
    text3 = """MODULE 3: SYSTEM DEADLOCKS

3.1 Necessary Conditions for Deadlock (Coffman Conditions)
A deadlock situation can arise if and only if the following four conditions hold simultaneously in a system:
1. Mutual Exclusion: At least one resource must be held in a non-shareable mode.
2. Hold and Wait: A process must be holding at least one resource and waiting to acquire additional resources held by other processes.
3. No Preemption: Resources cannot be preempted; a resource can be released only voluntarily by the process holding it after completing its task.
4. Circular Wait: A closed chain of processes exists such that each process holds at least one resource needed by the next process in the chain.

3.2 Deadlock Prevention vs Avoidance
- Prevention: Invalidate at least one of the four necessary conditions. (e.g., impose total ordering on resource allocation to prevent circular wait).
- Avoidance: Ensure dynamically that the system never enters an unsafe state.

3.3 Banker's Algorithm for Deadlock Avoidance
Developed by Edsger Dijkstra for multi-instance resource systems:
Data Structures:
- Available[m]: Vector of length m indicating available instances of resource type Rj.
- Max[n][m]: Maximum demand of each process Pi for resource Rj.
- Allocation[n][m]: Number of resources of each type currently allocated to Pi.
- Need[n][m]: Remaining resource need of Pi. Need[i][j] = Max[i][j] - Allocation[i][j].

Safety Algorithm Steps:
1. Let Work = Available and Finish[i] = False for all i = 0, 1, ..., n-1.
2. Find an index i such that:
   Finish[i] == False and Need[i] <= Work.
   If no such i exists, go to Step 4.
3. Work = Work + Allocation[i]
   Finish[i] = True
   Go to Step 2.
4. If Finish[i] == True for all i, then the system is in a SAFE STATE.
"""
    page3.insert_textbox(rect, text3, fontsize=10, fontname="helv")

    doc.save(output_path)
    doc.close()
    print(f"Sample PDF created at {output_path}")

